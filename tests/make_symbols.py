#!/usr/bin/env python3
"""Build js/symbols.js — the built-in symbol library.

The symbols are placeholders: you drop one in to say "an icon goes here".
They come from two open collections:

  Lucide       https://lucide.dev          ISC licence
  Simple Icons https://simpleicons.org      CC0 licence

Both are free to redistribute. The brand marks in Simple Icons are the real
ones, used as placeholders in the way a mockup uses them.

Run it to refresh the library:

    python3 tests/make_symbols.py
"""

import json
import os
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "js", "symbols.js")

LUCIDE = "https://unpkg.com/lucide-static@1.61.0/icons/{}.svg"
SIMPLE = "https://unpkg.com/simple-icons@16.36.0/icons/{}.svg"

# Panel and instrument symbols.
LUCIDE_NAMES = [
    "gauge", "activity", "circle-dot", "disc", "radio", "antenna", "toggle-right",
    "toggle-left", "power", "power-off", "battery", "battery-charging", "zap",
    "lightbulb", "thermometer", "fan", "sun", "moon", "cloud", "wind", "droplet",
    "flame", "snowflake", "compass", "waves", "siren", "triangle-alert", "circle-alert",
    "info", "life-buoy", "crosshair", "timer", "clock", "wrench", "cog", "sliders-horizontal",
    "square", "circle", "hexagon", "triangle", "pentagon", "box", "layers", "panels-top-left",
    "panel-top", "monitor", "smartphone", "car", "fuel", "navigation", "speedometer",
]

# The places a link goes.
LUCIDE_LINK = [
    "link", "at-sign", "mail", "message-circle", "send", "share-2", "globe", "rss",
    "bookmark", "thumbs-up", "heart", "star", "shopping-bag", "shopping-cart", "credit-card",
    "user", "users", "search", "bell", "settings", "menu", "home", "folder", "file-text",
    "download", "upload", "trash-2", "edit-3", "eye", "lock", "key-round", "plus", "minus",
    "check", "x", "arrow-right", "arrow-left", "arrow-up", "arrow-down", "chevron-right",
    "move", "maximize-2", "refresh-cw", "play", "pause", "circle-play", "video", "image",
    "type", "square-dashed", "rows-3", "columns-3",
]

# The brands.
BRANDS = [
    "discord", "x", "github", "youtube", "instagram", "linkedin", "facebook", "tiktok",
    "slack", "reddit", "twitch", "spotify", "mastodon", "bluesky", "telegram", "whatsapp",
    "signal", "vimeo", "pinterest", "medium", "threads", "codeberg", "stackoverflow", "matrix",
]

# The ink the symbols are drawn in. Mid grey, so they read on a light board and
# on a dark one.
INK = "#9aa4b8"


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": "napkinetic/1.0"})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read().decode("utf-8")


def fetch_all(names, template, folder):
    out = []
    for name in names:
        try:
            svg = fetch(template.format(name))
        except Exception as err:  # a missing icon should not stop the build
            print("  skipped {}: {}".format(name, err))
            continue
        svg = " ".join(svg.split())
        if "<svg" not in svg:
            print("  skipped {}: not an svg".format(name))
            continue
        # The collections use currentColor, or nothing at all, which an <img>
        # cannot inherit. A mid grey reads on a light board and on a dark one.
        svg = svg.replace("currentColor", INK)
        if "fill=" not in svg:
            svg = svg.replace("<svg ", '<svg fill="' + INK + '" ', 1)
        out.append({
            "name": name,
            "label": name.replace("-", " ").title(),
            "group": folder,
            "svg": svg,
        })
    return out


def main():
    print("fetching lucide symbols...")
    symbols = fetch_all(LUCIDE_NAMES, LUCIDE, "symbols")
    symbols += fetch_all(LUCIDE_LINK, LUCIDE, "symbols")
    print("fetching brand symbols...")
    symbols += fetch_all(BRANDS, SIMPLE, "brands")

    body = json.dumps(symbols, separators=(",", ":"))
    source = """/* Napkinetic — the built-in symbol library.

   A small collection of placeholders you can drop on the board to say what
   belongs there: an icon, a brand mark, a control. They are not artwork, and
   they are not a design system — they are here so a board can be marked up
   before the real thing exists.

   Lucide       https://lucide.dev        ISC licence
   Simple Icons https://simpleicons.org    CC0 licence

   Generated by tests/make_symbols.py — do not edit by hand. */
(function (MN) {
  "use strict";

  const SYMBOLS = %s;

  /* The id a symbol keeps across sessions, so a saved board still finds it. */
  function idFor(name) {
    return "sym-" + name;
  }

  function find(name) {
    return SYMBOLS.find(function (s) { return s.name === name; }) || null;
  }

  function urlFor(name) {
    const symbol = find(name);
    if (!symbol) return null;
    return "data:image/svg+xml," + encodeURIComponent(symbol.svg);
  }

  /* Put the library in the tray, unless the board already has it. */
  function install() {
    const existing = new Set(MN.state.state.assets.map(function (a) { return a.id; }));
    for (const symbol of SYMBOLS) {
      if (existing.has(idFor(symbol.name))) continue;
      MN.state.state.assets.push({
        id: idFor(symbol.name),
        name: symbol.label,
        path: "library/" + symbol.group + "/" + symbol.name + ".svg",
        mime: "image/svg+xml",
        width: 24,
        height: 24,
        blob: null,
        url: urlFor(symbol.name),
        builtin: true,
        missing: false,
      });
    }
  }

  MN.symbols = { SYMBOLS: SYMBOLS, install: install, urlFor: urlFor, idFor: idFor, find: find };
})(window.MN = window.MN || {});
""" % body

    with open(OUT, "w") as handle:
        handle.write(source)
    print("wrote {} ({} symbols, {} KB)".format(OUT, len(symbols), len(source) // 1024))


if __name__ == "__main__":
    main()
